import json
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
import jet

REC = os.path.join(jet.ROOT, 'docs', 'receipts', 'g5')
OUT = os.path.join(REC, 'design.md')


def load(*p):
    f = os.path.join(REC, *p)
    return json.load(open(f, encoding='utf-8')) if os.path.exists(f) else None


def n(x, k=3):
    return f'{x:.{k}g}' if isinstance(x, float) else str(x)


def main():
    cyc = jet.CYC
    rg = load('run1', 'cycle_realgas.json')
    st = load('fem', 'stress.json')
    rn = load('running', 'running.json')
    ro = load('modes', 'rotor.json')
    tb = load('modes', 'turbine_blade.json')
    fp = load('fuel', 'paths.json')
    lp = load('lube', 'paths.json')
    rd = load('review', 'readiness.json')
    L = ['# G5 micro turbojet: design document', '',
         'Generated by `tools/g5/doc.py` from the receipts it cites; every number is labelled MEASURED (published data with its source), COMPUTED (a stated calculation) or PROJECTED (an assumption).', '',
         '## Design point', '',
         '| Quantity | Value | Label | Source |', '|---|---|---|---|']
    for k, lab in (('PR', 'COMPUTED (design choice)'), ('eta_c', 'PROJECTED'), ('eta_t', 'PROJECTED'), ('TIT_K', 'COMPUTED (design choice)'), ('mdot_kg_s', 'COMPUTED (design choice)')):
        L.append(f'| {k} | {cyc["inputs"][k]} | {lab} | tools/g5/cycle.py |')
    for k in ('thrust_N', 'shaft_rpm', 'tip_speed_m_s', 'T2_K', 'T5_K', 'fuel_flow_g_s', 'tsfc_g_per_kN_s', 'nozzle_exit_dia_mm'):
        L.append(f'| {k} | {cyc[k]} | COMPUTED | docs/receipts/g5/run1/cycle.json (constant-cp deck) |')
    if rg:
        r = rg['result']
        L.append(f"| thrust_N (real gas) | {n(r['thrust_N'], 4)} | COMPUTED | cycle_realgas.json: NASA TM-4513 polynomials, complete Jet-A combustion |")
        L.append(f"| tsfc_g_per_kN_s (real gas) | {n(r['tsfc_g_kN_s'] if 'tsfc_g_kN_s' in r else r['tsfc_g_per_kN_s'], 4)} | COMPUTED | cycle_realgas.json |")
    L += ['', '## Materials', '', '| Part node | Grade | Source |', '|---|---|---|']
    for node, g in sorted(jet.GRADES.items()):
        name = jet.grade_name(node)
        bm = jet.BRG['materials'].get(name)
        src = (f"MEASURED: MIL-HDBK-5J Table {jet.STD[name]['table']} p{jet.STD[name]['page']}" if name in jet.STD else
               (f"MEASURED: {bm.get('source', jet.BRG['materials']['source'])} (Poisson PROJECTED)" if bm else 'PROJECTED: typed values'))
        L.append(f'| {node} | {name} | {src} |')
    L += ['', '## Bearings', '', f"SKF 708 CE/HCP4A, {jet.BEARING['d']} x {jet.BEARING['D']} x {jet.BEARING['B']} mm, {jet.BEARING['balls']} Si3N4 balls of {jet.BEARING['ball_d']} mm, attainable speed {jet.BEARING['n_oil_air_rpm']} r/min oil-air (MEASURED, data/std/bearings.json) against {cyc['shaft_rpm']} r/min (COMPUTED)."]
    if st:
        L += ['', '## Stress and creep (COMPUTED, tools/g5/stress.py)', '', '| Item | State | Stress MPa | Allowable MPa | Creep life h | Result |', '|---|---|---|---|---|---|']
        for r in st['rows']:
            L.append(f"| {r['item']} | {r['state']} | {r['stress_MPa']} | {r['allowable_MPa']} | {r.get('rupture_life_h') or ''} | {'pass' if r['ok'] else 'fail'} |")
    if rn:
        L += ['', '## Running clearances (cold CERTIFIED by the kernel, growth COMPUTED)', '', '| Pair | Cold mm | Closure mm | Running mm | Result |', '|---|---|---|---|---|']
        for r in rn['rows']:
            L.append(f"| {r['pair']} | {n(r['cold_certified_mm'][0], 4)} | {r['closure_mm']} | {r['running_mm']} | {r['status']} |")
    if ro:
        L += ['', '## Rotor dynamics (kernel `rotor`)', '', f"Critical speeds {[round(c) for c in ro['critical_speeds_rpm']]} r/min against {ro['design_rpm']} r/min; bearing radial stiffness {n(ro['bearing']['k_radial_N_per_mm'], 4)} N/mm COMPUTED by Hertz contact at a PROJECTED {ro['bearing']['preload_N']} N preload."]
    if tb:
        L += ['', '## Turbine blade modes (kernel `modes`)', '', f"Modes {[round(m['est']) for m in tb['modes']]} Hz; Campbell crossings in 50-110% speed: {[(c['mode'], c['eo'], round(c['crossing_rpm'])) for c in tb['campbell'] if c['in_range_50_110']] or 'none'}."]
    for name, p in (('Fuel path', fp), ('Lubrication path', lp)):
        if p:
            L += ['', f'## {name} (kernel `classify` along the route)', '']
            for r in p['paths']:
                L.append(f"- {r['name']}: {'connected' if r['connected'] else 'BLOCKED'}, {r['samples']} samples, narrowest bore {r['min_section_mm2']} mm2; {r['route']}")
    if rd:
        L += ['', '## Readiness', '', f"`tools/g5/readiness.py`: {sum(c['status'] == 'pass' for c in rd['checks'])}/{len(rd['checks'])} pass.", '']
        L += [f"- {c['status']}: {c['check']} - {c['evidence']}" for c in rd['checks']]
    open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(L) + '\n')
    print('wrote', OUT, len(L), 'lines')


if __name__ == '__main__':
    main()
