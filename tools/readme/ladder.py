import glob
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
R = os.path.join(ROOT, 'docs', 'receipts')
BEGIN, END = '<!-- ladder:begin (generated by tools/readme/ladder.py from docs/receipts) -->', '<!-- ladder:end -->'


def load(*p):
    with open(os.path.join(R, *p), encoding='utf-8') as f:
        return json.load(f)


def graded(rows):
    ok = sum(1 for r in rows if r.get('pass_') or r.get('status') == 'PASS')
    dfr = sum(1 for r in rows if r.get('status') == 'DEFERRED')
    return ok, len(rows) - ok - dfr, dfr


def g1():
    runs = sorted(glob.glob(os.path.join(R, 'g1', 'rerun-2026-10-27', 'run*', 'grade.json')))
    ps = [json.load(open(p)).get('verdict') == 'PASS' for p in runs]
    return f'{"✅ passed" if ps and all(ps) else "❌ failed"}: {sum(ps)}/{len(ps)} runs re-graded PASS (`docs/receipts/g1/rerun-2026-10-27`)'


def g2():
    ok, bad, d = graded(load('g2', 'run1', 'grade.json'))
    return f'{"✅ passed" if not bad else "❌ failed"}: run 1 graded {ok}/{ok + bad + d} by OCCT reading the exported STEP (`docs/receipts/g2/run1`)'


def g3():
    g = load('g3', 'v3', 'grade.json')
    return f'{"✅ passed" if g.get("pass") else "❌ failed"}: v3 gearbox, every part valid={g.get("all_valid")}, interference pairs {len(g.get("interference", []))} (`docs/receipts/g3/v3`)'


def g4():
    ok, bad, d = graded(load('g4', 'run2', 'grade.json'))
    return f'{"✅ passed" if not bad else "❌ not passed"}: run 2 graded {ok} pass, {bad} fail, {d} deferred of {ok + bad + d} (`docs/receipts/g4/run2`)'


def g5():
    r = load('g5', 'review', 'readiness.json')
    c = load('g5', 'run1', 'cycle.json')
    n = sum(1 for x in r['checks'] if x['status'] == 'pass')
    fail = sum(1 for x in r['checks'] if x['status'] == 'fail')
    return (f'in progress: readiness {n}/{len(r["checks"])} pass, {fail} fail (`docs/receipts/g5/review/readiness.json`); '
            f'design point {c["thrust_N"]} N at {c["shaft_rpm"]:,} r/min (`cycle.json`)')


def g6():
    g = load('g6', 'grading.json')
    m = load('g6', 'mass.json')
    c = load('g6', 'certs.json') if os.path.exists(os.path.join(R, 'g6', 'certs.json')) else {'rows': []}
    a = load('g6', 'asm.json')
    t = load('g6', 'tess.json') if os.path.exists(os.path.join(R, 'g6', 'tess.json')) else {'rows': []}
    tok = sum(r['verdict'] == 'pass' for r in t['rows'])
    tcur = t.get('design') == m.get('design')
    ok = sum(x['status'] == 'pass' for x in g['checks'])
    cok = sum(r['verdict'] == 'pass' for r in c['rows'])
    kg = m.get('total_kg') or m.get('partial_total_kg')
    cur = a.get('design') == m.get('design')
    itf = a.get('interference', 'not run')
    itf = itf if itf in ('none', 'not run') else f'{len(itf)} non-disjoint pairs' if isinstance(itf, list) else 'output not parsed'
    done = cur and c.get("design") == m.get("design") and g.get('ready') and c.get('green') and a.get('dof') == 0 and itf == 'none' and tcur and t.get('green')
    asm = (f'mates dof {a.get("dof")}, interference {itf}' if cur else
           f'mates and interference not yet re-run on {os.path.basename(m.get("design", "?"))} (last: {os.path.basename(a.get("design", "?"))})')
    return (f'{"✅ passed" if done else "in progress"}: OCCT grading of the STEP exports {ok}/{len(g["checks"])} pass (`docs/receipts/g6/grading.json`); '
            f'certified clearance and wall queries {cok}/{len(c["rows"])}{"" if c.get("design") == m.get("design") else " on " + os.path.basename(c.get("design", "?"))} (`certs.json`); {asm} (`asm.json`); '
            f'flow-path meshes closed at the manufacturing preset {tok}/{len(t["rows"])}{"" if tcur else " on " + os.path.basename(t.get("design", "?"))} (`tess.json`); '
            f'dry mass {kg[0]:.3f} kg certified{"" if m.get("complete") else " (partial)"} against {m["limit_kg"]} kg (`mass.json`)')


def bn(x):
    return os.path.basename(x or '?')


def briefs():
    s = load('briefs', 'summary.json')
    rows = s['rows']
    ok = sum(1 for r in rows if r.get('passed'))
    return (f'{"✅ done" if ok == len(rows) else "open"}', f'{ok}/{len(rows)} pass on {bn(s.get("binary"))} (`docs/receipts/briefs/summary.md`)')


def g5_row():
    r = load('g5', 'review', 'readiness.json')
    n = sum(1 for x in r['checks'] if x['status'] == 'pass')
    bad = [x['check'] for x in r['checks'] if x['status'] != 'pass']
    return (f'{"✅ done" if not bad else "open"}', f'{n}/{len(r["checks"])} pass on {bn(r.get("binary"))}; open: {"; ".join(bad) or "none"} (`docs/receipts/g5/review/readiness.json`)')


def g6_row():
    g = load('g6', 'grading.json')
    rn = load('g6', 'running.json')
    green = g6().startswith('✅') and rn.get('ok')
    fresh = g.get('grader') == 'fresh-session'
    state = '✅ done' if green and fresh else 'self-graded' if green else 'open'
    run = 'running clearances pass' if rn.get('ok') else 'running clearances fail: ' + '; '.join(x['pair'] for x in rn['rows'] if not x['ok'])
    return (state, g6().split(': ', 1)[1] + f'; {run} (`running.json`)')


def g6a_row():
    g = load('gates', 'g6a.json')
    sm = g['summary']
    n = sum(1 for c in g['checks'] if c['status'] == 'pass')
    p95 = next((c['evidence'] for c in g['checks'] if c['check'].startswith('p95')), '')
    return (f'{"✅ done" if g.get("ready") else "open"}', f'{n}/{len(g["checks"])} checks on {bn(g.get("binary"))}: commit {sm["committed"]}/{sm["ops"]} = {100 * sm["commit_rate"]:.1f}%, {p95} (`docs/receipts/gates/g6a.json`)')


def speed_row():
    s = load('briefs', 'summary.json')
    t = load('g6', 'tess.json')
    bud = ('budget_edit', 'budget_part', 'budget_export')
    miss = [f'{r["id"]} {k[7:]}' for r in s['rows'] for k in bud if r.get(k) != 'pass']
    slow = [f'{r["part"]} {r["seconds"]:.0f} s' for r in t['rows'] if r['seconds'] > s['budgets']['export_s']]
    ok = not miss and not slow
    return (f'{"✅ done" if ok else "open"}', f'briefs missing a budget: {", ".join(miss) or "none"}; G6 manufacturing meshes over 5 min: {", ".join(slow) or "none"} (`summary.md`, `g6/tess.json`)')


def earlier_row():
    rs = [g1(), g2(), g3(), g4()]
    ok = all(r.startswith('✅') for r in rs)
    return (f'{"✅ done" if ok else "open"}', 'G1 bracket, G2 pump housing, G3 gearbox, G4 blower: ' + '; '.join(r.split(': ', 1)[1] for r in rs))


ROWS = [('Brief ladder B1-B14', briefs), ('G5 micro turbojet readiness', g5_row), ('G6 HUMPHREY-1 (graded by a fresh session)', g6_row),
        ('G6a robustness', g6a_row), ('Speed budgets', speed_row), ('Earlier gates', earlier_row)]


def table():
    rows = ['| Measure (`docs/finish.md`) | State | Evidence |', '|---|---|---|'] + [f'| {g} | {a} | {b} |' for g, f in ROWS for a, b in [f()]]
    return '\n'.join([BEGIN] + rows + [END])


if __name__ == '__main__':
    p = os.path.join(ROOT, 'README.md')
    s = open(p, encoding='utf-8').read()
    if BEGIN in s:
        new = re.sub(re.escape(BEGIN) + '.*?' + re.escape(END), lambda m: table(), s, flags=re.S)
    else:
        m = re.search(r'\| \| Challenge \| Status \|\n\|---\|---\|---\|\n(?:\|.*\|\n)+', s)
        new = s[:m.start()] + table() + '\n' + s[m.end():]
    if '--check' in sys.argv:
        print('README ladder matches the receipts' if new == s else 'README ladder is stale: run python3 tools/readme/ladder.py')
        sys.exit(0 if new == s else 1)
    open(p, 'w', encoding='utf-8').write(new)
    print(table())
