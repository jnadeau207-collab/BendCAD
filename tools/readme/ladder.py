import glob
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
R = os.path.join(ROOT, 'docs', 'receipts')
BEGIN, END = '<!-- ladder:begin (generated by tools/readme/ladder.py from docs/receipts) -->', '<!-- ladder:end -->'


def load(*p):
    with open(os.path.join(R, *p), encoding='utf-8') as f:
        return json.load(f)


def graded(rows):
    ok = sum(1 for r in rows if r.get('pass_') or r.get('status') == 'PASS')
    dfr = sum(1 for r in rows if r.get('status') == 'DEFERRED')
    return ok, len(rows) - ok - dfr, dfr


def g1():
    runs = sorted(glob.glob(os.path.join(R, 'g1', 'rerun-2026-10-27', 'run*', 'grade.json')))
    ps = [json.load(open(p)).get('verdict') == 'PASS' for p in runs]
    return f'{"✅ passed" if ps and all(ps) else "❌ failed"}: {sum(ps)}/{len(ps)} runs re-graded PASS (`docs/receipts/g1/rerun-2026-10-27`)'


def g2():
    ok, bad, d = graded(load('g2', 'run1', 'grade.json'))
    return f'{"✅ passed" if not bad else "❌ failed"}: run 1 graded {ok}/{ok + bad + d} by OCCT reading the exported STEP (`docs/receipts/g2/run1`)'


def g3():
    g = load('g3', 'v3', 'grade.json')
    return f'{"✅ passed" if g.get("pass") else "❌ failed"}: v3 gearbox, every part valid={g.get("all_valid")}, interference pairs {len(g.get("interference", []))} (`docs/receipts/g3/v3`)'


def g4():
    ok, bad, d = graded(load('g4', 'run1', 'grade.json'))
    return f'{"✅ passed" if not bad else "❌ not passed"}: run 1 graded {ok} pass, {bad} fail, {d} deferred of {ok + bad + d} (`docs/receipts/g4/run1`)'


def g5():
    r = load('g5', 'review', 'readiness.json')
    c = load('g5', 'run1', 'cycle.json')
    n = sum(1 for x in r['checks'] if x['status'] == 'pass')
    fail = sum(1 for x in r['checks'] if x['status'] == 'fail')
    return (f'in progress: readiness {n}/{len(r["checks"])} pass, {fail} fail (`docs/receipts/g5/review/readiness.json`); '
            f'design point {c["thrust_N"]} N at {c["shaft_rpm"]:,} r/min (`cycle.json`)')


ROWS = [('G1', 'Parameterized mounting bracket with curved edges and holes', g1),
        ('G2', 'Flanged pump housing: bolt pattern, gasket groove, fits certified over tolerances', g2),
        ('G3', 'Two-stage gearbox: gears, shafts, bearings, housing, seals', g3),
        ('G4', 'Centrifugal blower with modal analysis and machining checks', g4),
        ('G5', 'A ~100 N micro turbojet, with drawings a shop can build from', g5),
        ('G6', 'A bespoke jet engine from a performance brief', lambda: 'not started')]


def table():
    rows = ['| | Challenge | Status |', '|---|---|---|'] + [f'| {g} | {c} | {f()} |' for g, c, f in ROWS]
    return '\n'.join([BEGIN] + rows + [END])


if __name__ == '__main__':
    p = os.path.join(ROOT, 'README.md')
    s = open(p, encoding='utf-8').read()
    if BEGIN in s:
        new = re.sub(re.escape(BEGIN) + '.*?' + re.escape(END), lambda m: table(), s, flags=re.S)
    else:
        m = re.search(r'\| \| Challenge \| Status \|\n\|---\|---\|---\|\n(?:\|.*\|\n)+', s)
        new = s[:m.start()] + table() + '\n' + s[m.end():]
    if '--check' in sys.argv:
        print('README ladder matches the receipts' if new == s else 'README ladder is stale: run python3 tools/readme/ladder.py')
        sys.exit(0 if new == s else 1)
    open(p, 'w', encoding='utf-8').write(new)
    print(table())
