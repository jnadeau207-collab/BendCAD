import json
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
import humphrey as H

REC = os.path.join(H.ROOT, 'docs', 'receipts', 'g6')
OUT = os.path.join(REC, 'design.md')


def load(name):
    f = os.path.join(REC, name)
    return json.load(open(f, encoding='utf-8')) if os.path.exists(f) else None


def n(x, k=4):
    return f'{x:.{k}g}' if isinstance(x, float) else str(x)


def table(head, rows):
    return ['| ' + ' | '.join(head) + ' |', '|' + '---|' * len(head)] + ['| ' + ' | '.join(str(c) for c in r) + ' |' for r in rows]


RISKS = [
    ('Combustor-turbine interface loss', 'MEASURED: 5% total-pressure loss across the guide-vane ring behind an RDC (Welsh et al. rigs, as charged by the brief)',
     'charged in full in the cycle deck (`docs/receipts/g6/cycle.json`); the vane passages turn 68 degrees over 45 mm to attenuate outflow unsteadiness', 'the deck still cannot close TSFC (refusal g6-tsfc-not-closed)'),
    ('Turbine efficiency under unsteady inflow', 'MEASURED: a T63 axial turbine ran behind an RDC for more than 20 min cumulative without damage or a significant efficiency penalty (Naples, Hoke and Battelle, ASME JEGTP 141(2), 2019)',
     'turbine efficiency debited 2 points (0.84 to 0.82) in the Humphrey deck', 'the debit is a choice, not a measurement at this scale'),
    ('Injector-detonation coupling and mode control', 'MEASURED: annular rigs run as rapid deflagration below phi about 0.5 and detonate stably above about 0.82 (brief section 2)',
     '120 injector orifices of 1.2 mm on the injector face; start and part power on deflagration', 'wave count and mode are not controlled by any modelled part'),
    ('Fuel preparation', 'MEASURED: liquid-kerosene RDC operation needed pre-vaporisation, hydrogen addition of 9-13% by mass, oxygen enrichment or 707-765 K air (brief section 2)',
     'four exhaust-heated Inconel 625 vaporiser coils on the nozzle shell; a 2 mm wall AISI 304 tank for the hydrogen pilot', 'the cell-size requirement is not met with 10% hydrogen energy (refusal g6-rdc-cell-size-not-fit)'),
    ('Thermal durability', 'MEASURED: the longest continuous RDC runs anywhere are about 300 s with hydrogen (brief section 4.6)',
     'SiC/SiC stator (measured N24A properties, NASA TM-2009-215806; design strain limit 0.3%, Morscher and Pujar)', 'this gate certifies a design, not a service life'),
    ('Turbine tip clearance', 'COMPUTED: closure of the Waspaloy rotor inside the SiC/SiC shroud (`docs/receipts/g6/running.json`)',
     'none inside the brief: the shroud must be part of the CMC monolith', 'refusal g6-turbine-tip-clearance'),
    ('Starting', 'MEASURED: deflagration below phi about 0.5 in the rig record (brief section 2)', 'start sequence state: air start on the starter, hydrogen pilot ignition, deflagration to idle, then transition above phi 0.82',
     'the transition has never been demonstrated in a turbojet'),
    ('NOx', 'unknown: no published NOx data for kerosene RDC in a turbojet was found in the free sources used', 'none modelled', 'unknown'),
]


def main():
    cy, rd, sz, rn = load('cycle.json'), load('rdc.json'), load('sizing.json'), load('running.json')
    ms, asm, ro = load('mass.json'), load('asm.json'), load('rotor.json')
    refusals = [cy['refusal']] if cy and cy.get('refusal') else []
    refusals += [rd['refusal']] if rd and rd.get('refusal') else []
    refusals += rn['refusals'] if rn else []
    if ms and ms.get('refusal'):
        refusals.append(ms['refusal'])
    for r in (load('certs.json') or {}).get('rows', []):
        if r['verdict'] != 'pass':
            refusals.append(dict(code='g6-certified-query-failed', target=f"{r['query']} certified, design {r['design_mm']} mm", computed=f"{r['certified_mm']} {r['status']}", physics=r['why']))
    for c in (load('grading.json') or {}).get('checks', []):
        if c['status'] != 'pass':
            refusals.append(dict(code='g6-export-disagrees', target=c['check'], computed=c['evidence'], physics='the STEP export read back by OCCT disagrees with the model or the deck'))
    L = ['# HUMPHREY-1: design document', '',
         'Generated by `tools/g6/doc.py` from the receipts in `docs/receipts/g6`. Every number is labelled MEASURED (published test data, cited), COMPUTED (this deck or the kernel, assumptions stated) or PROJECTED (study claims or assumptions). The engine has never been built; its TSFC is COMPUTED everywhere it appears.', '',
         '## Outcome', '']
    L += [f"- **Refusal {r['code']}**: target {r['target']}; computed {r['computed']}; physics: {r['physics']}" for r in refusals] or ['- no refusal']
    if cy:
        b, h = cy['brayton'], cy['humphrey_measured_rdc']
        L += ['', '## 1. Cycle deck (COMPUTED, `tools/g6/deck.py`)', '']
        L += table(['quantity', 'Brayton (4% burner loss)', 'Humphrey (best measured RDC gain, 5% vane loss)'],
                   [(k, n(b[k]), n(h[k])) for k in ('PR', 'TIT_K', 'p4_kPa', 'T5_K', 'specific_thrust_N_s_kg', 'mdot_kg_s', 'tsfc_lb_lbf_h', 'thermal_eff')])
        L += ['', f"Target TSFC {cy['target_tsfc_lb_lbf_h']} lb/lbf/h; TJ150 datasheet {cy['tj150_tsfc_lb_lbf_h']} (MEASURED). Simulated RDC gains (PROJECTED) are listed in the receipt and are not credited."]
    if sz:
        c, t = sz['compressor'], sz['turbine']
        L += ['', '## 2. Compressor sizing (COMPUTED, `tools/g6/sizing.py`)', '',
              f"Tip speed {n(c['tip_speed_m_s'])} m/s (limit {c['tip_limit_m_s']}), D2 {n(c['D2_mm'])} mm, inducer tip {n(c['inducer_tip_mm'])} mm at hub/tip {c['inducer_hub_tip']}, {c['blades']}, slip {n(c['slip'])}, {n(c['shaft_rpm'])} r/min; {c['diffuser']}."]
        L += ['', '## 4. Turbine sizing (COMPUTED)', '',
              f"Loading {t['loading_psi']}, flow coefficient {t['flow_coeff_phi']}, mean speed {n(t['mean_speed_m_s'])} m/s, blade height {n(t['blade_height_mm'])} mm, hub {n(t['hub_radius_mm'])} mm, tip {n(t['tip_radius_mm'])} mm."]
    if rd:
        L += ['', '## 3. RDC sizing (COMPUTED, `tools/g6/rdc.py`)', '']
        L += table(['case', 'cell mm', 'waves', 'fill cells', 'fill height mm', 'fill m/s', 'channel mm', 'channel/cell', 'fits'],
                   [(r['case'], r['lambda_mm'], r['waves'], r['fill_factor'], r['fill_height_mm'], r['fill_velocity_m_s'], r['channel_width_mm'], r['channel_over_cell'], r['fits']) for r in rd['rows'][:8]])
        L += ['', 'Sources: ' + '; '.join(f'{k}: {v}' for k, v in rd['sources'].items())]
    if rn:
        L += ['', '## 4b. Running tip clearances (COMPUTED, `tools/g6/running.py`)', '']
        L += table(['pair', 'cold mm', 'closure mm', 'running mm', 'result'], [(r['pair'], n(r['cold_mm']), n(r['closure_mm']), n(r['running_mm']), 'pass' if r['ok'] else 'fail') for r in rn['rows']])
    L += ['', '## 5. Rotordynamics', '']
    if ro:
        L += [f"Critical speeds (COMPUTED, kernel `rotor`, `tools/g6/rotor.py`): {', '.join(f'{c:.0f}' for c in ro['critical_speeds_rpm'])} r/min against the {H.RPM:.0f} r/min design point; "
              f"within 15%: {ro['within_15pct'] or 'none'}. The front support is a back-to-back pair of 7004 ACE/HCP4A at z {H.Z_BRG_F2:.0f} and {H.Z_BRG_F:.0f} mm: with one front bearing the third critical sat at 43 690 r/min, 0.35% from the design point. "
              f"Bearing radial stiffness {ro['bearing']['k_radial_N_per_mm']:.0f} N/mm each ({ro['bearing']['method']}; preload {ro['bearing']['preload_N']} N, PROJECTED)."]
        L += table(['disc', 'mass kg', 'residual unbalance g mm', 'force N', 'front bearing N', 'rear bearing N'],
                   [(k, next(round(d['m_kg'], 3) for d in ro['discs'] if d['name'] == k), round(v['residual_unbalance_g_mm'], 2), round(v['force_N'], 1), round(v['front_N'], 1), round(v['rear_N'], 1))
                    for k, v in ro['balance']['discs'].items()])
        L += ['', f"Balance: {ro['balance']['grade']} ({ro['balance']['basis']}). Provisions: {ro['provisions']}."]
    else:
        L += ['not-analyzed: the kernel `rotor` run on the built design has not completed']
    L += ['', '## Mass properties certificate', '']
    if ms:
        L += table(['part', 'material', 'mass kg (certified interval)'], [(p['name'], p['material'], p['mass_kg']) for p in ms['parts']])
        miss = [f"{p['name']} ({(p.get('error') or 'no result')[:90]})" for p in ms['parts'] if not p.get('mass_kg')]
        L += ['', f"Total {ms['total_kg']} kg against {H.SZ['envelope']['mass_max_kg']} kg." if ms.get('complete') else
              f"Incomplete: {ms['partial_total_kg'][0]:.3f} kg certified over the parts that evaluated, against {H.SZ['envelope']['mass_max_kg']} kg. Not evaluated: {'; '.join(miss)}."]
    else:
        L += ['not-analyzed: the per-part kernel mass run on the built design has not completed']
    L += ['', '## Assembly', '']
    L += [f"dof {asm['dof']}; interference: {asm.get('interference', 'not run')}"] if asm else ['not-analyzed: `asm solve` and `asm interf` on the built design have not completed']
    ce, gr, pm = load('certs.json'), load('grading.json'), load('pmi.json')
    L += ['', '## Semantic PMI and tolerance stacks (COMPUTED by the kernel `pmi`, `tools/g6/pmi.py`)', '']
    L += table(['item', 'verb', 'result', 'kernel output'], [(r['name'], r['verb'], r['verdict'], r['out'].replace('\n', '; ')[:220]) for r in pm['rows']]) + ['', pm['notes']] if pm else ['not-analyzed']
    L += ['', '## Certified queries (COMPUTED by the kernel, `tools/g6/certs.py`)', '']
    L += table(['query', 'design mm', 'certified interval mm', 'status', 's', 'result'],
               [(r['query'], r['design_mm'], r['certified_mm'], r['status'], r['seconds'], r['verdict']) for r in ce['rows']]) if ce else ['not-analyzed']
    L += ['', '## Independent grading of the STEP AP242 export (`tools/g6/grade.py`)', '',
          'OCCT reads every exported part back and measures it; it shares no code with the kernel. The gate asks for a fresh agent session as the grader; the owner forbids subagents, so the grader is this independent code path.', '']
    L += table(['check', 'result', 'evidence'], [(c['check'], c['status'], c['evidence']) for c in gr['checks']]) if gr else ['not-analyzed']
    L += ['', '## Materials', '']
    L += table(['node', 'grade', 'source'], [(k, v if isinstance(v, str) else v[0], 'MIL-HDBK-5J (data/std/materials.json)' if isinstance(v, str) else ('NASA TM-2009-215806 (data/std/cmc.json)' if 'SIC' in v[0] else 'data/std/bearings.json'))
                                            for k, v in sorted(H.GRADES.items()) if k in H.USED])
    L += ['', '## 6. Risk register', '']
    L += table(['risk', 'evidence', 'mitigation in the model', 'residual exposure'], RISKS)
    open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(L) + '\n')
    print('wrote', OUT, len(L), 'lines;', len(refusals), 'refusals')


if __name__ == '__main__':
    main()
